// Bake the sprite atlas: node tools/bake.mjs            -> assets/atlas*.png + assets/atlas.js
//                        node tools/bake.mjs --preview house out.png  -> contact sheet only
// Uses the headless Chromium that ships with Playwright; no paid services.
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
const require = createRequire(import.meta.url);
const { chromium } = (() => { try { return require("playwright"); } catch { return require("/opt/node22/lib/node_modules/playwright"); } })();

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage();
page.on("console", m => { if (!m.text().includes("willReadFrequently") && (m.type() === "warning" || m.type() === "error")) console.log("[page]", m.text()); });
page.on("pageerror", e => { console.error(e); process.exitCode = 1; });
await page.goto("file://" + path.join(root, "tools/art/bake.html"));

const save = (file, dataUrl) => fs.writeFileSync(file, Buffer.from(dataUrl.split(",")[1], "base64"));
if (args[0] === "--preview") {
  const url = await page.evaluate(([f, c, s, k]) => bakePreview(f, c, s, k), [args[1] || "", +(args[3] || 6), +(args[4] || 260), +(args[5] || 1)]);
  save(args[2] || "preview.png", url);
  console.log("wrote", args[2] || "preview.png");
} else {
  const res = await page.evaluate(() => bakeAll());
  fs.mkdirSync(path.join(root, "assets"), { recursive: true });
  for (const f of fs.readdirSync(path.join(root, "assets"))) if (/^atlas\d+\.png$/.test(f)) fs.unlinkSync(path.join(root, "assets", f));
  const files = res.pages.map((u, i) => { const f = `assets/atlas${i}.png`; save(path.join(root, f), u); return f; });
  // Lossless recompression if Pillow is available.
  try { execFileSync("python3", ["-c", "import sys\nfrom PIL import Image\nfor f in sys.argv[1:]:\n  Image.open(f).save(f, optimize=True)", ...files.map(f => path.join(root, f))]); } catch { }
  const js = `// Generated by tools/bake.mjs — do not edit. Sprite atlas index:\n// key: [page, x, y, w, h, anchorX, anchorY, bakeScale] (anchor in world px)\nwindow.ATLAS = ${JSON.stringify({ pages: files, sprites: res.meta })};\n`;
  fs.writeFileSync(path.join(root, "assets/atlas.js"), js);
  const kb = files.reduce((n, f) => n + fs.statSync(path.join(root, f)).size, 0) / 1024;
  console.log(`baked ${res.count} sprites into ${files.length} page(s), ${Math.round(kb)} KB, ${res.ms} ms`);
}
await browser.close();
